#!/usr/bin/env bash
# PreToolUse (Edit|Write|MultiEdit): guards files that must not be hand-edited, and keeps Ozone out of client code.
set -euo pipefail

input=$(cat)
root="${CLAUDE_PROJECT_DIR:-$(pwd)}"
file=$(jq -r '.tool_input.file_path // empty' <<<"$input")
[[ -z $file ]] && exit 0
rel="${file#"$root"/}"
# Text being written: Write content, Edit new_string, or every MultiEdit new_string.
text=$(jq -r '[.tool_input.content, .tool_input.new_string, (.tool_input.edits // [] | .[].new_string)] | map(select(. != null)) | join("\n")' <<<"$input")

decide() { # decision, reason
  jq -n --arg d "$1" --arg r "$2" '{hookSpecificOutput: {hookEventName: "PreToolUse", permissionDecision: $d, permissionDecisionReason: $r}}'
  exit 0
}

case "$rel" in
  core/data/schemas/*)
    decide deny "core/data/schemas is generated by the Room compiler. Change the entity, bump AppDatabase.version, add a migration, and let the build regenerate the schema JSON."
    ;;
  */detekt-baseline.xml | detekt-baseline.xml)
    decide deny "Don't hand-edit detekt baselines. Fix the finding, or ask the user before regenerating with ./gradlew detektBaseline."
    ;;
  server/appview/src/main/resources/db/migration/V*.sql)
    if git -C "$root" ls-files --error-unmatch -- "$rel" >/dev/null 2>&1; then
      decide ask "$rel is a committed Flyway migration. Editing it breaks Flyway's checksum on any database that already applied it (including the local appview-db volume). Normally add the next V<n+1>__*.sql instead. Approve only if you intend to rewrite history and reset appview-db."
    fi
    ;;
esac

# Ozone (or any atproto SDK) has no wasmJs target. Client code uses the hand-written XRPC layer in core/atproto.
case "$rel" in
  core/* | composeApp/* | webApp/* | androidApp/* | web/* | iosApp/*)
    if grep -qiE 'sh\.christian\.ozone|libs\.ozone|ozone-' <<<"$text"; then
      decide deny "No Ozone or other atproto SDK in client code: Ozone has no wasmJs target. Use the hand-written XRPC layer in core/atproto."
    fi
    ;;
esac
exit 0
