-- admin/admin-site: operators' sessions on the admin site (only a hash of each session secret) and the audit log of their actions.
CREATE TABLE admin_sessions (
    token_hash VARCHAR(64) NOT NULL PRIMARY KEY,
    did VARCHAR(255) NOT NULL,
    csrf_token VARCHAR(64) NOT NULL,
    created_at BIGINT NOT NULL,
    expires_at BIGINT NOT NULL
);
CREATE INDEX admin_sessions_expires_idx ON admin_sessions (expires_at);

CREATE TABLE admin_actions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    admin_did VARCHAR(255) NOT NULL,
    action_name VARCHAR(128) NOT NULL,
    target VARCHAR(512),
    params TEXT NOT NULL,
    outcome VARCHAR(255) NOT NULL,
    acted_at BIGINT NOT NULL
);
CREATE INDEX admin_actions_at_idx ON admin_actions (acted_at, id);
CREATE INDEX admin_actions_admin_idx ON admin_actions (admin_did, acted_at, id);
