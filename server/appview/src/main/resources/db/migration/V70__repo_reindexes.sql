-- admin/repo-reindex: one row per reindex of an account, queued by an operator, run by RepoReindexer. Identifiers, the repo revision,
-- counts, times, states and short error codes only, never record content. Kept 90 days.
CREATE TABLE repo_reindexes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    did VARCHAR(255) NOT NULL,
    requested_by VARCHAR(255) NOT NULL,
    requested_at BIGINT NOT NULL,
    resync_spaces BOOLEAN NOT NULL DEFAULT TRUE,
    started_at BIGINT,
    finished_at BIGINT,
    -- queued, running, succeeded, failed or unavailable.
    run_state VARCHAR(16) NOT NULL,
    -- resolving, fetching, applying, removing or spaces, while running.
    phase VARCHAR(16),
    rev VARCHAR(32),
    car_bytes BIGINT,
    records_seen INTEGER NOT NULL DEFAULT 0,
    records_unchanged INTEGER NOT NULL DEFAULT 0,
    records_indexed INTEGER NOT NULL DEFAULT 0,
    records_invalid INTEGER NOT NULL DEFAULT 0,
    records_removed INTEGER NOT NULL DEFAULT 0,
    records_live INTEGER NOT NULL DEFAULT 0,
    spaces_resynced INTEGER,
    error_code VARCHAR(32),
    error_message VARCHAR(512)
);

CREATE INDEX repo_reindexes_did ON repo_reindexes (did, requested_at);
CREATE INDEX repo_reindexes_state ON repo_reindexes (run_state, requested_at);
