#!/usr/bin/env bash
# PreToolUse (write_to_file|replace_file_content|Edit|Write|MultiEdit):
# Guards files that must not be hand-edited, and keeps Ozone out of client code.
set -euo pipefail

input=$(cat)
root="${CLAUDE_PROJECT_DIR:-$(git rev-parse --show-toplevel 2>/dev/null || pwd)}"

# Support Antigravity (TargetFile) and Claude (file_path)
file=$(jq -r '.toolCall.args.TargetFile // .tool_input.file_path // empty' <<<"$input")
# Claude Code rejects a top-level "decision" other than approve/block, so only Antigravity gets one.
claude=$(jq 'has("tool_input")' <<<"$input")
allow() { [[ $claude == true ]] || echo '{"decision": "allow"}'; exit 0; }
[[ -z $file ]] && allow

# Normalize relative path
rel="${file#"$root"/}"

# Text being written
text=$(jq -r '[
  .toolCall.args.CodeContent,
  .toolCall.args.ReplacementContent,
  .tool_input.content,
  .tool_input.new_string,
  (.tool_input.edits // [] | .[].new_string)
] | map(select(. != null)) | join("\n")' <<<"$input")

decide() { # decision, reason
  if [[ $claude == true ]]; then
    jq -n --arg d "$1" --arg r "$2" '{hookSpecificOutput: {hookEventName: "PreToolUse", permissionDecision: $d, permissionDecisionReason: $r}}'
  else
    jq -n --arg d "$1" --arg r "$2" '{decision: $d, reason: $r}'
  fi
  exit 0
}

case "$rel" in
  core/data/schemas/*)
    decide deny "core/data/schemas is generated by the Room compiler. Change the entity, bump AppDatabase.version, add a migration, and let the build regenerate the schema JSON."
    ;;
  */detekt-baseline.xml | detekt-baseline.xml)
    decide deny "Don't hand-edit detekt baselines. Fix the finding, or ask the user before regenerating with ./gradlew detektBaseline."
    ;;
  server/appview/src/main/resources/db/migration/V*.sql)
    if git -C "$root" ls-files --error-unmatch -- "$rel" >/dev/null 2>&1; then
      decide ask "$rel is a committed Flyway migration. Editing it breaks Flyway's checksum on any database that already applied it (including the local appview-db volume). Normally add the next V<n+1>__*.sql instead. Approve only if you intend to rewrite history and reset appview-db."
    fi
    ;;
esac

# Ozone (or any atproto SDK) has no wasmJs target. Client code uses the hand-written XRPC layer in core/atproto.
case "$rel" in
  core/* | app/* | composeApp/* | webApp/* | androidApp/* | web/* | iosApp/*)
    if grep -qiE 'sh\.christian\.ozone|libs\.ozone|ozone-' <<<"$text"; then
      decide deny "No Ozone or other atproto SDK in client code: Ozone has no wasmJs target. Use the hand-written XRPC layer in core/atproto."
    fi
    ;;
esac

# Kotlin explicit backing fields replace the `private val _x = Mutable…` + `val x = _x.asStateFlow()` pair.
case "$rel" in
  *.kt)
    if grep -qE 'private[[:space:]]+(val|var)[[:space:]]+_[A-Za-z0-9]+[^=]*=[[:space:]]*(Mutable|mutable)' <<<"$text"; then
      decide deny "Use an explicit backing field instead of a private _underscore property: \`val x: StateFlow<T>\` followed by \`field = MutableStateFlow(...)\` on the next line (works for List/MutableList etc. too). Inside the class, \`x\` smart-casts to the mutable type."
    fi
    if grep -qE '\.as(State|Shared)Flow\(\)' <<<"$text"; then
      decide ask "asStateFlow()/asSharedFlow() usually means a backing-property pair. Prefer an explicit backing field (\`val x: StateFlow<T>\` + \`field = MutableStateFlow(...)\`). Approve only if the mutable flow lives in another object."
    fi
    ;;
esac

allow
